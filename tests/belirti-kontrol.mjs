import { boot, sleep } from './lib.mjs';
const { b, p, errs } = await boot();
p.setDefaultTimeout(30000); p.on('dialog', d => d.accept());
await p.evaluate(() => closeProfileModal()); await sleep(1000);
await p.evaluate(() => { try { finishVitaSpotlightTour(true); } catch (e) {} });
const results = []; const log = (n, ok, d) => { results.push(ok); console.log((ok ? 'OK   ' : 'FAIL ') + n + (d ? ' -> ' + d : '')); };
await p.evaluate(() => navigateToView('view-neyim')); await sleep(300);
await p.evaluate(() => document.querySelectorAll('.anamnesis-card').forEach(c => { const m = (c.getAttribute('onclick') || '').match(/toggleAnamnesisCard\(this,\s*'([^']+)'\)/); if (m && ['numbness', 'hair_loss'].includes(m[1])) c.click(); })); await sleep(300);
const q = () => p.evaluate(() => ({ vis: !!document.querySelector('#symptomDailyCheck.sdc'), rows: document.querySelectorAll('#symptomDailyCheck .sdc-r').length, syms: [...state.selectedSymptoms], stored: JSON.parse(localStorage.getItem('vitatakip_symptoms_' + activeUserId) || '[]') }));
await p.evaluate(() => { localStorage.removeItem('vitatakip_symptomcheck_' + activeUserId); navigateToView('view-home'); }); await sleep(500);
let s = await q();
log('Kart görünür, 2 belirti satırı', s.vis && s.rows === 2, JSON.stringify(s));
await p.evaluate(() => document.querySelector('#symptomDailyCheck .sdc-no').click()); await sleep(400);
s = await q();
log('"Geçti" belirtiyi kaldırır (durum + kayıt)', s.syms.length === 1 && s.stored.length === 1 && s.rows === 1, JSON.stringify(s));
await p.evaluate(() => document.querySelector('#symptomDailyCheck .sdc-all').click()); await sleep(300);
s = await q();
log('"Hepsi aynı" kartı kapatır, belirti korunur', !s.vis && s.syms.length === 1);
await p.evaluate(() => { navigateToView('view-labs'); navigateToView('view-home'); }); await sleep(300);
s = await q(); log('Aynı gün tekrar sormaz', !s.vis);
await p.evaluate(() => { localStorage.setItem('vitatakip_symptomcheck_' + activeUserId, new Date(Date.now() - 86400000).toLocaleDateString('tr-TR')); localStorage.setItem('vitatakip_lastActiveDate_' + activeUserId, new Date(Date.now() - 86400000).toLocaleDateString('tr-TR')); window.dispatchEvent(new Event('focus')); }); await sleep(600);
s = await q(); log('Ertesi gün yeniden sorar', s.vis && s.rows === 1);
await p.evaluate(() => document.querySelector('#symptomDailyCheck .sdc-no').click()); await sleep(400);
s = await q(); log('Son belirti kalkınca kart kapanır', !s.vis && s.syms.length === 0);
log('Hata yok', errs.length === 0, errs.join(' | '));
console.log('ÖZET', results.filter(Boolean).length + '/' + results.length);
await b.close(); process.exit(0);
